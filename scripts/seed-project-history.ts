async function main() {
  await ensureWikiStructureTables();

  const result = await importWikiPageSeed({
    slug: SLUG,
    title: TITLE,
    content_html: CONTENT_HTML,
  });

  const sql = getSql();
  const page = await getWikiPageBySlug(SLUG);
  if (!page) {
    throw new Error("Сторінку не знайдено після імпорту");
  }

  await sql`
    UPDATE wiki_pages
    SET summary = ${SUMMARY}, updated_at = NOW()
    WHERE id = ${page.id}
  `;

  await sql`
    UPDATE wiki_category_pages
    SET card_blurb = ${"Хронологія за значними подіями: відкриття, річниці, вайп."}
    WHERE page_id = ${page.id}
  `;

  try {
    revalidateWikiPublic();
  } catch {
    /* ignore */
  }

  console.log(
    `Історія_проєкту: ${result}; id=${page.id}; chars=${CONTENT_HTML.length}`,
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
